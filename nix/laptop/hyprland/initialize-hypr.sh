#!/usr/bin/env bash
set -euo pipefail

target="${HYPR_CONFIG_TARGET:-$HOME/.config/hypr}"
repo_dir="${1:?usage: initialize-hypr <repo-config-dir>}"

mkdir -p "$target"

created=()

write_file() {
  local name=$1
  local destination=$target/$name

  if [ -e "$destination" ]; then
    return 0
  fi

  cat > "$destination"
  created+=("$name")
}

write_file hyprland.lua <<LUA
local config_dir = os.getenv("HOME") .. "/.config/hypr"
local repo_dir = "$repo_dir"

package.path = repo_dir .. "/?.lua;" .. config_dir .. "/?.lua;" .. package.path

dofile(repo_dir .. "/hyprland.lua")
LUA

write_file colors.lua <<'LUA'
return {
	active_border = {
		"rgba(33ccffee)",
		"rgba(00ff99ee)",
	},
	inactive_border = "rgba(595959aa)",
	group_active = "rgba(33ccffee)",
	group_inactive = "rgba(595959aa)",
	group_locked = "rgba(00ff99ee)",
	text = "rgba(eeeeeeff)",
	background = "rgba(0e0e0eff)",
	surface = "rgba(141414ff)",
	surface_high = "rgba(1e1e1eff)",
	shadow = "rgba(1a1a1aee)",
	launcher = "rgba(1a1a1af2)",
}
LUA

write_file hyprmon.lua <<'LUA'
-- Generated by HyprMon. Manual changes may be overwritten.
LUA

if ((${#created[@]} > 0)); then
  echo "initialize-hypr: created ${created[*]} in $target"
fi
