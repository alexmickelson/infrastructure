#!/usr/bin/env bash
set -euo pipefail
shopt -s nullglob

target="${HYPR_CONFIG_TARGET:-$HOME/.config/hypr}"
source_dir="${1:?usage: initialize-hypr <config-dir>}"

mkdir -p "$target"

created=()

for source in "$source_dir"/*; do
  name=${source##*/}
  destination=$target/$name

  if [ -e "$destination" ]; then
    continue
  fi

  install -m 0644 "$source" "$destination"
  created+=("$name")
done

write_default() {
  local name=$1
  local destination=$target/$name

  if [ -e "$destination" ]; then
    return 0
  fi

  cat > "$destination"
  created+=("$name")
}

write_default colors.lua <<'LUA'
return {
	active_border = {
		"rgba(33ccffee)",
		"rgba(00ff99ee)",
	},
	inactive_border = "rgba(595959aa)",
	group_active = "rgba(33ccffee)",
	group_inactive = "rgba(595959aa)",
	group_locked = "rgba(00ff99ee)",
	text = "rgba(eeeeeeff)",
	background = "rgba(0e0e0eff)",
	surface = "rgba(141414ff)",
	surface_high = "rgba(1e1e1eff)",
	shadow = "rgba(1a1a1aee)",
	launcher = "rgba(1a1a1af2)",
}
LUA

write_default hyprmon.lua <<'LUA'
-- Generated by HyprMon. Manual changes may be overwritten.
LUA

if ((${#created[@]} > 0)); then
  echo "initialize-hypr: created ${created[*]} in $target"
fi
